"""Security contract tests for Hartwell's staged Harbor boundary."""

import runpy
import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

HARTWELL = Path(__file__).parent
FEE_TASK = HARTWELL / "tasks" / "fee-dispute-reconstruction"
TASKS = tuple(sorted((HARTWELL / "tasks").iterdir()))
STAGE_MODULE: dict[str, object] = runpy.run_path(str(HARTWELL / "harbor_stage.py"))
INSTALL_SH: str = str(STAGE_MODULE["INSTALL_SH"])
ORACLE_EXECUTABLE: str = "/usr/local/libexec/workbench/oracle"


def test_installer_confines_oracle_to_root_mounted_solution() -> None:
    assert f"ORACLE={ORACLE_EXECUTABLE}" in INSTALL_SH
    assert 'test "$#" -eq 0' in INSTALL_SH
    assert "test -f /solution/solve.py" in INSTALL_SH
    assert "test ! -L /solution/solve.py" in INSTALL_SH
    assert "test ! -w /solution/solve.py" in INSTALL_SH
    assert "WORKBENCH_STATE=/home/environment/state" in INSTALL_SH
    assert "WORKBENCH_WORKSPACE=/home/agent/workspace" in INSTALL_SH
    assert "python3 /solution/solve.py" in INSTALL_SH
    assert 'chown environment:environment "$ORACLE"' in INSTALL_SH
    assert 'chmod 750 "$ORACLE"' in INSTALL_SH


def test_environment_owned_entrypoints_preserve_effective_uid() -> None:
    assert INSTALL_SH.count("'#!/bin/sh -p'") == 2
    assert "'# Generated by the task installer. The MCP surface is the aperture.'" in (
        INSTALL_SH
    )
    assert '"$SERVE $tool"' in INSTALL_SH
    assert '"$SERVE $tool $@"' not in INSTALL_SH


def test_rendered_installer_is_valid_shell() -> None:
    with tempfile.TemporaryDirectory() as temporary:
        install = Path(temporary) / "install.sh"
        install.write_text(INSTALL_SH)
        subprocess.run(["sh", "-n", str(install)], check=True)


def test_installer_proves_normal_agent_cannot_inject_or_widen_oracle() -> None:
    assert 'agent -c "mkdir /solution"' in INSTALL_SH
    assert "run-as-environment /bin/cat" in INSTALL_SH
    assert f"run-as-environment {ORACLE_EXECUTABLE} /bin/cat" in INSTALL_SH


def test_solution_keeps_privileged_read_and_agent_write_on_opposite_sides() -> None:
    solve = (FEE_TASK / "solution" / "solve.sh").read_text()
    assert f'/usr/local/bin/run-as-environment {ORACLE_EXECUTABLE} > "$TEMP"' in solve
    assert 'mv -f "$TEMP" dispute.json' in solve
    assert "run-as-environment python3" not in solve


def test_reference_handoffs_are_readable_by_the_verifier_group() -> None:
    for task in TASKS:
        solve = (task / "solution" / "solve.sh").read_text()
        assert 'chmod 640 "$TEMP"' in solve, task.name
        assert solve.index('chmod 640 "$TEMP"') < solve.index('mv -f "$TEMP"')


@pytest.mark.skipif(shutil.which("docker") is None, reason="docker is unavailable")
def test_allowlisted_shell_preserves_environment_effective_uid() -> None:
    completed = subprocess.run(
        [
            "docker",
            "run",
            "--rm",
            "--entrypoint",
            "/bin/sh",
            "workbench:dev",
            "-c",
            "\n".join(
                [
                    "set -eu",
                    "printf '%s\\n' '#!/bin/sh -p' 'id -u' "
                    "> /usr/local/libexec/workbench/euid",
                    "chown environment:environment /usr/local/libexec/workbench/euid",
                    "chmod 750 /usr/local/libexec/workbench/euid",
                    "su -s /bin/sh agent -c 'run-as-environment "
                    "/usr/local/libexec/workbench/euid'",
                ]
            ),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    assert completed.stdout.strip() == "10000"


@pytest.mark.skipif(shutil.which("docker") is None, reason="docker is unavailable")
def test_real_staged_task_installs_with_mcp_ready_and_boundary_intact() -> None:
    environment = FEE_TASK / "environment"
    if not (environment / ".workbench" / "install.sh").is_file():
        pytest.skip("materialize the Hartwell tasks before the container regression")

    command = "\n".join(
        [
            "set -eu",
            "sh /home/agent/workspace/.workbench/install.sh",
            "su -s /bin/sh agent -c 'test ! -r /home/environment/state/clio.db'",
            "su -s /bin/sh agent -c "
            "'test ! -r /opt/workbench-runtime/workbench/tools/serve.py'",
            "if su -s /bin/sh agent -c 'run-as-environment /bin/cat "
            "/home/environment/state/clio.db' >/dev/null 2>&1; then exit 20; fi",
            "if su -s /bin/sh agent -c 'run-as-environment "
            "/usr/local/libexec/workbench/oracle /bin/cat' "
            ">/dev/null 2>&1; then exit 21; fi",
            "printf 'staged-ready\\n'",
        ]
    )
    container = subprocess.run(
        [
            "docker",
            "create",
            "--entrypoint",
            "/bin/sh",
            "workbench:dev",
            "-c",
            command,
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    try:
        subprocess.run(
            ["docker", "cp", f"{environment}/.", f"{container}:/home/agent/workspace"],
            check=True,
            capture_output=True,
            text=True,
        )
        completed = subprocess.run(
            ["docker", "start", "--attach", container],
            capture_output=True,
            text=True,
        )
        assert completed.returncode == 0, completed.stderr
        assert completed.stdout.strip() == "staged-ready"
    finally:
        subprocess.run(
            ["docker", "rm", "--force", container],
            check=True,
            capture_output=True,
            text=True,
        )
